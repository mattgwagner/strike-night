// One headless browser joins, adds two bots, and checks they move and shoot.
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_DIR ?? 'playwright');
const url = process.argv[2] ?? 'http://127.0.0.1:5192';
const out = process.argv[3] ?? 'e2e/out';
mkdirSync(out, { recursive: true });
const room = 'e2e-' + Math.random().toString(36).slice(2, 7);
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM ?? '/usr/bin/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errs = [];
const p = await browser.newPage({ viewport: { width: 960, height: 600 } });
p.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 300)); });
p.on('pageerror', e => errs.push(e.message));
await p.goto(`${url}/?room=${room}&name=Solo&skin=astro&w=semi`);
await p.click('button.go');
await p.waitForFunction(() => window.strike && window.strike.myId > 0, null, { timeout: 15000 });
await p.evaluate(() => { window.strike.input.locked = true; window.strike.setPaused(false); window.strike.net.send({ t: 'admin', cmd: 'bots', arg: 2 }); });
await p.waitForFunction(() => window.strike.remotes.size === 2, null, { timeout: 10000 });
const snap = () => p.evaluate(() => [...window.strike.remotes.values()].map(r => ({ name: r.name, bot: r.bot, p: r.p.map(n => +n.toFixed(1)), hp: r.hp })));
const s0 = await snap();
await p.waitForTimeout(6000);
const s1 = await snap();
console.log('bots t0', JSON.stringify(s0));
console.log('bots t6', JSON.stringify(s1));
const moved = s0.map((b, i) => Math.hypot(b.p[0] - s1[i].p[0], b.p[2] - s1[i].p[2]).toFixed(1));
console.log('moved (m):', moved.join(', '));
const feed = await p.evaluate(() => [...document.querySelectorAll('.killfeed div')].map(d => d.textContent));
console.log('killfeed:', JSON.stringify(feed));
await p.screenshot({ path: `${out}/bots.png` });
console.log(errs.length ? errs.join('\n') : 'no console errors');
await browser.close();
